// Синтетический «Отчёт о реализации» (старый режим) в раскладке реального
// отчёта Ozon: двухстрочная шапка («Реализовано» / «Возвращено клиентом» над
// одинаково названными колонками), строка-нумерация, итоговые строки. Все
// подписи — t="str" (числовые ссылки &#x…;), без r-атрибутов: ровно те ячейки,
// которые портит SheetJS 0.18.5. Данные вымышленные.

import { buildOzonStyleXlsx, EMPTY, TXT } from "./xlsx-builder.mjs";

const W = 13;
const blank = () => Array.from({ length: W }, () => null);
const line = (col, text) => {
  const r = blank();
  r[col] = text;
  return r;
};

/** Товары: [№, название, артикул, SKU, код, продано ₽, выплаты G, шт, цена, возврат ₽, выплаты K, шт, цена]. */
export const REALIZATION_PRODUCTS = [
  [1, "Товар А", "ART-A", 1000000001, "CODE-A", 1000.0, 10.25, 3, 333.33, 300.0, 3.0, 1, 300.0],
  [2, "Товар Б", "ART-B", 1000000002, "CODE-B", 500.0, 5.0, 1, 500.0, null, null, null, null],
  [3, "Товар В", "ART-C", 1000000003, "CODE-C", 250.5, 0, 2, 125.25, null, null, null, null],
];

export function buildRealizationXlsx() {
  const num = (v) => (v === null ? null : v);
  const rows = [
    blank(),
    blank(),
    line(2, TXT("Отчет о реализации № 1 от 30.06.2026")),
    line(2, TXT("Реализация товаров за период с 01.06.2026 по 30.06.2026")),
    line(2, TXT("по Договору оферты для Продавцов на Платформе OZON № T-1 от 01.01.2020")),
    ...Array.from({ length: 7 }, blank), // 5..11
    // 12: группы над колонками
    [
      TXT("№ п/п"),
      TXT("Название товара"),
      TXT("Артикул"),
      TXT("SKU"),
      TXT("Код товара Ozon"),
      TXT("Реализовано"),
      null,
      null,
      null,
      TXT("Возвращено клиентом"),
      null,
      null,
      null,
    ],
    // 13: одинаково названные колонки (G и K различаются только группой выше)
    [
      EMPTY,
      EMPTY,
      EMPTY,
      EMPTY,
      EMPTY,
      TXT("Реализовано на сумму, руб."),
      TXT("Выплаты по механикам лояльности партнёров, руб."),
      TXT("Кол-во"),
      TXT("Цена реализации, руб."),
      TXT("Возвращено на сумму, руб."),
      TXT("Выплаты по механикам лояльности партнёров, руб."),
      TXT("Кол-во"),
      TXT("Цена реализации, руб."),
    ],
    // 14: строка нумерации колонок
    Array.from({ length: W }, (_, i) => TXT(String(i + 1))),
    // 15..17: товары
    ...REALIZATION_PRODUCTS.map((p) => p.map((v, i) => (i >= 1 && i <= 2 || i === 4 ? TXT(String(v)) : num(v)))),
    blank(),
    [null, TXT("Итого реализовано (за вычетом возвратов) (руб.):"), 1450.5, ...Array.from({ length: W - 3 }, () => null)],
    [null, TXT("Всего выплат от партнёров (руб.):"), 12.25, ...Array.from({ length: W - 3 }, () => null)],
    blank(),
    line(1, TXT("М.П.")),
  ];
  return buildOzonStyleXlsx(rows, { sheetName: "Отчет о реализации" });
}
