import { NextResponse } from "next/server";

// ============================================================================
// /api/ozon/profit-draft — ОТКЛЮЧЁН / DEPRECATED (PR #20.1).
//
// Раньше этот роут отдавал ПОЛНЫЙ предварительный API-расчёт чистой прибыли
// (apiTotals / costDraft / preliminary / netProfitPreview) без сохранения и без
// списания попытки. Это была дыра монетизации: имея право на расчёт (free trial,
// кредит или безлимит), пользователь мог бесконечно получать полный расчёт, ни
// разу не нажав «Сохранить» — и попытка не списывалась.
//
// Гейт по entitlement (PR #20) уменьшал, но НЕ закрывал утечку: пользователь С
// правом всё равно мог дёргать роут напрямую (в обход UI) и получать полный
// расчёт без списания. Поэтому роут ПОЛНОСТЬЮ отключён.
//
// Теперь полный API-расчёт доступен ТОЛЬКО через единое действие «Рассчитать и
// сохранить» — POST /api/ozon/save-calculation, где сервер проверяет доступ,
// пересчитывает с нуля, проверяет полноту себестоимости, СПИСЫВАЕТ ровно одну
// попытку (для активного безлимита — без списания) и сохраняет результат в
// историю. Только после успешного сохранения возвращаются цифры. UI этот preview
// больше не вызывает.
//
// Этот эндпоинт НЕ обращается к Ozon API, НЕ расшифровывает ключ, НЕ читает
// каталог, НЕ считает прибыль и НЕ возвращает никаких цифр — только 410 Gone с
// кодом deprecated_flow. Так прямой вызов в обход UI не может стать обходным
// путём к бесплатному полному расчёту.
// ============================================================================

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

const NO_STORE = { "Cache-Control": "no-store" } as const;

const GONE = {
  code: "deprecated_flow",
  message:
    "Полный API-расчёт доступен только через сохранение расчёта (POST /api/ozon/save-calculation).",
} as const;

// 410 Gone — эндпоинт намеренно удалён из обращения. Никаких данных, никаких
// обращений к внешним системам: ни цифр, ни Ozon API, ни ключа, ни каталога.
export async function POST() {
  return NextResponse.json(GONE, { status: 410, headers: NO_STORE });
}

// Прямые GET-пробы — тоже 410, без какой-либо нагрузки.
export async function GET() {
  return NextResponse.json(GONE, { status: 410, headers: NO_STORE });
}
